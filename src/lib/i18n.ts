export type Copy = typeof fa;
export type ErrorKey = keyof Copy["errors"];
export type WarningCode = keyof Copy["warnings"];
export const getCopy = (language: Language): Copy => language === "en" ? en : fa;
export const getDirection = (language: Language) => language === "en" ? "ltr" : "rtl";
export const formatNumber = (value: number, language: Language, options?: Intl.NumberFormatOptions) =>
  value.toLocaleString(language === "en" ? "en-US" : "fa-IR", options);

export function formatBytes(value: number, language: Language) {
  return value < 1024 * 1024
    ? `${formatNumber(Math.max(1, Math.round(value / 1024)), language)} ${language === "en" ? "KB" : "کیلوبایت"}`
    : `${formatNumber(value / 1024 / 1024, language, { maximumFractionDigits: 1 })} ${language === "en" ? "MB" : "مگابایت"}`;
}

export function formatCount(value: number, unit: "row" | "cell" | "sheet" | "issue", language: Language) {
  const faUnits = { row: "ردیف", cell: "سلول", sheet: "برگه", issue: "مورد" };
  const label = language === "fa" ? faUnits[unit] : unit + (value === 1 ? "" : "s");
  return `${formatNumber(value, language)} ${label}`;
}

export function interpolate(message: string, values: Record<string, string | number>) {
  return message.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
}

export function downloadName(fileName: string, language: Language) {
  return language === "en" ? fileName.replace(/_پاکسازی‌شده(?=\.[^.]+$)/, "_cleaned") : fileName;
}
